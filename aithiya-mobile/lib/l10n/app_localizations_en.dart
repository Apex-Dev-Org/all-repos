      locale: localeName,
    );
    final String countString = countNumberFormat.format(count);

    String _temp0 = intl.Intl.pluralLogic(
      count,
      locale: localeName,
      other: 'Considering $countString attachments: ',
      one: 'Considering 1 attachment: ',
      zero: '',
    );
    return '$_temp0';
  }

